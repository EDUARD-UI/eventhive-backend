CREATE TABLE IF NOT EXISTS tokens_recuperacion_clave (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    fecha_expiracion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    fecha_uso TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_token_recuperacion_usuario
    ON tokens_recuperacion_clave(usuario_id);

CREATE TABLE IF NOT EXISTS invitaciones_rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo_invitado VARCHAR(150) NOT NULL,
    rol_destino VARCHAR(50) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_invitacion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    fecha_expiracion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    fecha_aceptacion TIMESTAMP WITHOUT TIME ZONE,
    invitado_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    organizacion_id BIGINT REFERENCES organizaciones(id)
);

CREATE INDEX IF NOT EXISTS idx_invitacion_rol_correo
    ON invitaciones_rol(correo_invitado);
